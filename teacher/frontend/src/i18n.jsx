const I18nContext = createContext({ language: "en", t: (key) => key });

export function I18nProvider({ language, children }) {
  const value = useMemo(() => ({
    language,
    t(key, variables = {}) {
      const template = messages[language]?.[key] || messages.en[key] || key;
      return Object.entries(variables).reduce((text, [name, replacement]) => text.replaceAll(`{{${name}}}`, String(replacement)), template);
    },
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
