export function localizeTask(task, language) {
  const localizationId = task.localizationId || task.id;
  if (task.taskCategory === "personalized") {
    return localizePersonalizedTask(
      task,
      language,
      taskZh[localizationId] || {},
      taskSignalZh[localizationId] || {},
    );
  }
  if (language !== "zh") return task;
  const localized = taskZh[localizationId] || {};
  const duration = localized.duration || task.duration;
  const due = localizedTaskDue(task, localized.due);
  const priority = task.priority === "New assignment" ? "新任务" : localized.priority;
  const shiwenContent = {
    reason: task.reason,
    result: task.result,
    standard: task.standard,
    value: task.value,
    steps: task.steps,
  };
  return {
    ...task,
    ...localized,
    ...taskSignalZh[localizationId],
    ...shiwenContent,
    sourceStage: task.sourceStage || task.stage,
    duration,
    due: due || task.due,
    priority: priority || task.priority,
    stage: localized.stage || (task.stage.startsWith("Day ") ? task.stage.replace("Day ", "第 ") + " 天" : task.stage),
  };
}

