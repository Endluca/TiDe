export function isAppEventName(value: string): value is AppEventName {
  return (APP_EVENT_NAMES as readonly string[]).includes(value);
}

export function clientCanWriteEvent(name: AppEventName): boolean {
  return !BACKEND_ONLY_EVENTS.has(name);
}

export function isSensitivePropertyName(name: string): boolean {
  const normalized = name.replace(/[^a-z0-9]/gi, '').toLowerCase();
  return SENSITIVE_PROPERTY_NAMES.some((part) => normalized.includes(part));
}
